export type DtKey = keyof typeof fr;
const dict = { fr, en };

/** Traduction du module Disponibilité (suit la langue courante de l'application). */
export function useDt() {
  const { lang } = useApp();
  return useCallback((key: DtKey): string => dict[lang === "en" ? "en" : "fr"][key] ?? fr[key] ?? key, [lang]);
}

const STATUS_LABEL_KEY: Record<string, DtKey> = {
  available: "st_available", limited: "st_limited", to_reconfirm: "st_to_reconfirm",
  contested: "st_contested", out: "st_out", unknown: "st_unknown",
};
/** Clé de traduction du libellé d'un état de disponibilité effectif. */
export function statusLabelKey(s: string): DtKey {
  return STATUS_LABEL_KEY[s] ?? "st_unknown";
}
