export function useV2() {
  const { lang } = useApp();
  return useCallback(
    (key: V2Key, vars?: Record<string, string | number>): string => {
      let s: string = (lang === "en" ? en[key] : fr[key]) ?? fr[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
}
